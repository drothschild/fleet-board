"""Boot registration for the persistent supervisor: service files, the per-user registry and
the boot entry that restores a domain after a reboot.

Rendering and status never need administrator rights and never call sudo. A real macOS
LaunchDaemon install does need them, so `install` prints the exact privileged commands for a
person to run instead of running them. The registry holds executable paths and environment
variable NAMES only; secret values are never written anywhere.

The boot entry goes through the same launcher/serve path as an explicit Start: there is no
second way to launch a service.
"""
