LAUNCHER = """#!/bin/bash
# Fleet Board supervisor boot entry. Generated by `supervisor service install`; do not edit.
# It lives outside the versioned plugin cache and reads the registry for the current runtime.
unset CDPATH
REG=$(cd "$(dirname "$0")/.." && pwd)
# credentials.env is read by the watcher on every tick (parsed, never sourced), so a fixed file
# takes effect without restarting this process.
PY=""
SCRIPTS=""
{ IFS= read -r PY; IFS= read -r SCRIPTS; } < "$REG/current" 2>/dev/null
if [ -z "$PY" ] || [ ! -x "$PY" ] || [ ! -d "$SCRIPTS" ]; then
  echo "fleet-board boot: the recorded python or plugin scripts are missing; run: supervisor service install" >&2
  printf '{"state":"waiting","reason":"missing_executable","message":"recorded python or plugin scripts are missing; reinstall or roll back"}\\n' > "$REG/runtime-status.json"
  exit 75
fi
rm -f "$REG/runtime-status.json"
PYTHONPATH="$SCRIPTS${PYTHONPATH:+:$PYTHONPATH}"
export PYTHONPATH
exec "$PY" -m supervisor.cli boot "$@"
"""


# -- identity and registry ---------------------------------------------------------------
def current_user():
    try:
        return pwd.getpwuid(os.getuid()).pw_name
    except KeyError:
        return getpass.getuser()


def plugin_version():
    manifest = Path(__file__).resolve().parents[2] / ".claude-plugin" / "plugin.json"
    try:
        return json.loads(manifest.read_text(encoding="utf-8")).get("version", "unknown")
    except (OSError, ValueError):
        return "unknown"


def _home(env):
    return Path(env.get("HOME") or Path.home())


def registry_dir(env=None):
    """FLEET_BOARD_REGISTRY_DIR, else ~/.fleet-board/supervisor-registry."""
    env = os.environ if env is None else env
    return Path(env.get("FLEET_BOARD_REGISTRY_DIR") or _home(env) / ".fleet-board" / "supervisor-registry")


def domain_key(root):
    """The registration key: derived from the domain id (paths.registry_key), the same value the
    service computes for its own domain, so a linked worktree is found by status."""
    return paths.registry_key(paths.domain_id_for_root(root))


def _key_for(root, reg):
    """domain_key, tolerating a repository that is currently missing: then the key is found by
    matching the recorded root, so a missing repo is reported, not lost."""
    try:
        return domain_key(root)
    except (OSError, ValueError):
        resolved = str(Path(root).resolve())
        for candidate in sorted((reg / "domains").glob("*.json")):
            found = _read_json(candidate)
            if isinstance(found, dict) and found.get("root") == resolved:
                return candidate.stem
        return hashlib.sha256(resolved.encode("utf-8")).hexdigest()[:12]


_ENTRY_KEYS = ("root", "key", "label", "unit", "kind", "platform", "user", "log_dir", "socket_dir")


def _load_entry(reg, key):
    """(entry, error): the domain's registration, or why it cannot be trusted. A malformed
    entry yields (None, error) and affects only itself."""
    path = reg / "domains" / (key + ".json")
    if not path.exists():
        return None, None
    entry = _read_json(path)
    activation = entry.get("activation") if entry else None
    if (entry is None or any(not isinstance(entry.get(k), str) for k in _ENTRY_KEYS)
            or not isinstance(entry.get("credentials", []), list) or not isinstance(activation, dict)
            or not isinstance(activation.get("destination"), str) or not isinstance(activation.get("rendered"), str)):
        return None, {"code": "registry_entry_invalid",
                      "message": "registry entry %s is malformed; run: supervisor service install" % path.name,
                      "at": None}
    return entry, None


def _private_dir(path):
    path = Path(path)
    if path.is_symlink():
        raise errors.Invalid("registry path is a symlink: %s" % path)
    path.mkdir(mode=0o700, parents=True, exist_ok=True)
    info = path.stat()
    if info.st_uid != os.getuid():
        raise errors.Invalid("registry path is not owned by this user: %s" % path)
    os.chmod(str(path), 0o700)
    return path


def _write(path, text, mode=0o600):
    path = Path(path)
    _private_dir(path.parent)
    fd, temp = tempfile.mkstemp(dir=str(path.parent), prefix=".tmp-")
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as stream:
            stream.write(text)
        os.chmod(temp, mode)
        os.replace(temp, str(path))
    except BaseException:
        try:
            os.unlink(temp)
        except OSError:
            pass
        raise


def _write_json(path, value):
    _write(path, json.dumps(value, indent=1, sort_keys=True) + "\n")


def _read_json(path):
    try:
        value = json.loads(Path(path).read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return None
    return value if isinstance(value, dict) else None


def _platform(value=None):
    value = value or sys.platform
    if value.startswith("darwin"):
        return "darwin"
    if value.startswith("linux"):
        return "linux"
    raise errors.Invalid("unsupported platform for boot registration: %s" % value)


def _names(root, key, platform, kind):
    label = "%s.%s" % (LABEL_PREFIX, key)
    if platform == "darwin" and kind == "login":
        label += ".login"
    return label, "fleet-board-supervisor-%s.service" % key


# -- rendering ---------------------------------------------------------------------------
def _xml(value):
    return (str(value).replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;"))


def _systemd_arg(value):
    """One double-quoted ExecStart word: backslash, quote, % and $ are the special characters."""
    value = str(value).replace("\\", "\\\\").replace('"', '\\"').replace("%", "%%").replace("$", "$$")
    return '"%s"' % value


def _systemd_env(name, value):
    value = str(value).replace("\\", "\\\\").replace('"', '\\"').replace("%", "%%")
    return 'Environment="%s=%s"' % (name, value)


def _fill(template, values):
    text = (_TEMPLATES / template).read_text(encoding="utf-8")
    for key, value in values.items():
        text = text.replace("@@%s@@" % key, value)
    return text


def render_launchd(label, argv, environment, log_path, home, username=None):
    arguments = "\n".join("    <string>%s</string>" % _xml(a) for a in argv)
    variables = "\n".join("    <key>%s</key>\n    <string>%s</string>" % (_xml(k), _xml(v))
                          for k, v in environment.items())
    user = "  <key>UserName</key>\n  <string>%s</string>" % _xml(username) if username else ""
    return _fill("launchd.plist", {"LABEL": _xml(label), "USERNAME": user, "ARGUMENTS": arguments,
                                   "ENVIRONMENT": variables, "LOG": _xml(log_path), "HOME": _xml(home)})


def render_systemd(description, argv, environment, log_path):
    return _fill("systemd.service", {
        "DESCRIPTION": description.replace("%", "%%").replace("\n", " "),
        "EXEC_START": " ".join(_systemd_arg(a) for a in argv),
        "ENVIRONMENT": "\n".join(_systemd_env(k, v) for k, v in environment.items()),
        "LOG": log_path.replace("%", "%%")})


# -- commands ----------------------------------------------------------------------------
def _run(runner, argv):
    """Run one unprivileged command. sudo is never run from here."""
    if argv[0] in ("sudo", "doas", "su"):
        raise errors.Invalid("refusing to run a privileged command: %s" % argv[0])
    try:
        done = runner(argv, stdin=subprocess.DEVNULL, capture_output=True, text=True, timeout=30)
    except (OSError, subprocess.SubprocessError) as exc:
        return {"argv": argv, "returncode": None, "error": str(exc), "stdout": ""}
    return {"argv": argv, "returncode": done.returncode, "stdout": done.stdout or "", "stderr": done.stderr or ""}


def _brief(result):
    return {k: result[k] for k in ("argv", "returncode", "error") if k in result}


def _linger(runner, user):
    result = _run(runner, ["loginctl", "show-user", user, "--property=Linger"])
    out = result.get("stdout", "")
    if result.get("returncode") == 0 and "Linger=yes" in out:
        return "enabled"
    if result.get("returncode") == 0 and "Linger=no" in out:
        return "missing"
    return "unknown"


def _executables(env):
    found = {"python": os.path.abspath(sys.executable)}
    for name in ("bash", "git", "jq", "gh", "claude"):
        hit = shutil.which(name, path=env.get("PATH") or os.defpath)
        if hit:
            found[name] = os.path.abspath(hit)
    return found


def _service_path(env, executables):
    entries = [os.path.dirname(p) for p in executables.values()]
    entries += [e for e in (env.get("PATH") or "").split(os.pathsep)]
    seen, result = set(), []
    for entry in entries:
        if entry and os.path.isabs(entry) and entry not in seen:
            seen.add(entry)
            result.append(entry)
    return os.pathsep.join(result or ["/usr/bin", "/bin"])


# -- credentials ---------------------------------------------------------------------------
CREDENTIALS_HINT = "credentials.env must be a regular file you own with mode 0600"


def _unquote(raw):
    raw = raw.strip()
    if len(raw) >= 2 and raw[0] == raw[-1] == "'":
        return raw[1:-1]
    if len(raw) >= 2 and raw[0] == raw[-1] == '"':
        return re.sub(r'\\([\\"$`])', r"\1", raw[1:-1])
    return raw.split()[0] if raw.split() else ""


def parse_credentials(text):
    """NAME=value lines (optional `export`, optional single or double quotes, `#` comments). Parsed
    as data: nothing in the file is ever executed or expanded."""
    values = {}
    for line in text.splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        line = re.sub(r"export\s+", "", line, count=1)
        name, sep, raw = line.partition("=")
        if sep and _NAME.match(name.strip()):
            values[name.strip()] = _unquote(raw)
    return values


def read_credentials(reg):
    """(values, problem) from <registry>/credentials.env, evaluated afresh each call. A file that
    is missing yields ({}, None); one that is not a private regular file yields ({}, why).

    The file is opened without following a symlink and checked on the open descriptor, so what is
    checked is what is read."""
    path = Path(reg) / "credentials.env"
    hint = "%s: %s" % (CREDENTIALS_HINT, path)
    try:
        # O_NONBLOCK so a FIFO planted here cannot hang the open; harmless for a regular file.
        fd = os.open(str(path), os.O_RDONLY | os.O_NOFOLLOW | os.O_NONBLOCK | getattr(os, "O_CLOEXEC", 0))
    except FileNotFoundError:
        return {}, None
    except OSError:
        return {}, hint  # a symlink (ELOOP), an unreadable file or anything else that is not plainly ours
    try:
        info = os.fstat(fd)
        if not stat.S_ISREG(info.st_mode) or info.st_uid != os.getuid() or info.st_mode & 0o077:
            return {}, hint
        with os.fdopen(fd, "rb", closefd=False) as stream:
            raw = stream.read()
    except OSError:
        return {}, "credentials.env cannot be read: %s" % path
    finally:
        os.close(fd)
    try:
        return parse_credentials(raw.decode("utf-8")), None
    except UnicodeDecodeError:
        return {}, "credentials.env is not valid UTF-8 text: %s" % path


def registered_credentials(reg, entry):
    """(values, problem) for a registered domain."""
    return read_credentials(reg)


# -- store inspection and compatibility ----------------------------------------------------
def _store_path(log_dir, root):
    return Path(log_dir) / "supervisor" / paths.domain_id_for_root(root) / "store.sqlite3"


def _read_store_file(db, cache=None):
    """What a runtime needs to know about a store, read-only: desired mode, newest event, newest
    start/resume, schema version and the runner protocol of every active attempt. None when the
    store does not exist yet. A newer schema is reported, not read further.

    A caller that reads repeatedly passes the same `cache` dict: only events after the cursor are
    read, so a tick costs the new events, not the whole log. The cursor is checked against the
    event it points at and restarts if the store was replaced or shrank."""
    db = Path(db)
    if not db.exists():
        return None
    cache = {} if cache is None else cache
    connection = sqlite3.connect("file:%s?mode=ro" % quote(str(db)), uri=True, timeout=10)
    try:
        schema = connection.execute("PRAGMA user_version").fetchone()[0]
        info = {"schema": schema, "mode": None, "newest": 0, "last_start": 0, "service_version": None,
                "active": 0, "runners": []}
        if schema not in (0, _store_schema()):
            return info
        row = connection.execute("SELECT desired_mode, service_version FROM domain").fetchone()
        info["mode"] = row[0] if row else None
        info["service_version"] = row[1] if row else None
        newest = info["newest"] = connection.execute("SELECT COALESCE(MAX(sequence),0) FROM events").fetchone()[0]
        cursor = cache.get("cursor", 0)
        if newest < cursor:
            cache.clear()
            cursor = 0
        if cursor:
            # The event the cursor points at must still be the one we saw (one row, not a scan).
            at = connection.execute("SELECT sequence,timestamp FROM events WHERE sequence >= ? "
                                    "ORDER BY sequence LIMIT 1", (cursor,)).fetchone()
            if at is None or at[0] != cursor or at[1] != cache.get("anchor"):
                cache.clear()  # the store was replaced under us: read it from the start
                cursor = 0
        last_start = cache.get("last_start", 0)
        reported = cache.setdefault("reported", {})
        # Only the two event types that matter, newest bound fixed first so the cursor stays exact.
        for sequence, kind, payload in connection.execute(
                "SELECT sequence,type,payload FROM events WHERE sequence > ? AND sequence <= ? "
                "AND type IN ('command','runner_version') ORDER BY sequence", (cursor, newest)):
            try:
                body = json.loads(payload)
            except ValueError:
                body = None
            if isinstance(body, dict):
                if kind == "command" and body.get("command") in ("start", "resume"):
                    last_start = sequence
                elif kind == "runner_version":
                    reported[body.get("runner_id")] = body.get("protocol")
        if newest > cursor:
            anchor = connection.execute("SELECT timestamp FROM events WHERE sequence >= ? ORDER BY sequence LIMIT 1",
                                        (newest,)).fetchone()
            cache.update(cursor=newest, anchor=anchor[0] if anchor else None)
        cache["last_start"] = last_start
        info["last_start"] = last_start
        marks = ",".join("?" * len(ACTIVE_ATTEMPT_STATES))
        for attempt_id, nonce, data in connection.execute(
                "SELECT id,nonce,data FROM attempts WHERE state IN (%s)" % marks, ACTIVE_ATTEMPT_STATES):
            try:
                recorded = json.loads(data).get("runner_protocol")
            except (ValueError, AttributeError):
                recorded = None
            if recorded is None:
                recorded = reported.get(attempt_id, reported.get(nonce))
            info["active"] += 1
            # An attempt created before the protocol was recorded ran on protocol 1, the only one
            # that has ever existed; it is never "unknown" (that would let a future runtime adopt it).
            info["runners"].append((attempt_id, 1 if recorded is None else recorded))
        return info
    finally:
        connection.close()


def _store_schema():
    from .store import SCHEMA_VERSION
    return SCHEMA_VERSION


def compatibility(info, live):
    """Every reason this runtime cannot safely serve the store and live service it finds, as
    [(reason, message)]. Compares real things: the store's schema, each active attempt's
    recorded runner protocol, and the protocol the live service reports."""
    problems = []
    hint = ("run `supervisor service rollback` to restore the previous runtime (add --restore-store only "
            "to also restore the store backed up before the upgrade); state is never wiped")
    if info is not None and info["schema"] not in (0, _store_schema()):
        problems.append(("incompatible_store", "store schema %r is not supported by this runtime (schema %d); %s"
                         % (info["schema"], _store_schema(), hint)))
    if info is not None:
        bad = sorted({str(p) for _id, p in info["runners"] if p not in RUNNER_PROTOCOLS})
        if bad:
            problems.append(("incompatible_runner", "active attempts use runner protocol %s but this runtime "
                             "adopts %s; %s" % (", ".join(bad), ", ".join(map(str, RUNNER_PROTOCOLS)), hint)))
    runtime = live.get("runtime") if isinstance(live, dict) else None
    if isinstance(runtime, dict) and runtime.get("protocol") not in (None, PROTOCOL_VERSION):
        problems.append(("incompatible_protocol", "the running service speaks protocol %r but this runtime "
                         "speaks %d; %s" % (runtime.get("protocol"), PROTOCOL_VERSION, hint)))
    return problems


def _live_status(root, entry):
    """The status of the service answering on this domain's socket, or None."""
    from . import cli
    try:
        path = paths.controller_socket(paths.domain_id_for_root(root), base=Path(entry["socket_dir"]))
        status = cli._socket_transport(path)({"command": "status"})
    except Exception:  # noqa: BLE001 - no answer (or an untrusted socket) means no usable live service
        return None
    return status if isinstance(status, dict) else None


def _hold_service_lock(db):
    """Take the domain's exclusive service lock (the one `serve` takes), or refuse. Returns the fd;
    closing it releases the lock. Only a restore holds it; the boot watcher never locks anything."""
    directory = Path(db).parent
    directory.mkdir(mode=0o700, parents=True, exist_ok=True)
    fd = os.open(str(directory / "service.lock"), os.O_CREAT | os.O_RDWR, 0o600)
    try:
        fcntl.flock(fd, fcntl.LOCK_EX | fcntl.LOCK_NB)
    except OSError:
        os.close(fd)
        raise errors.Invalid("a service is running for this domain; stop it before restoring the store")
    return fd


def _backup_store(db, target):
    """A consistent copy of the store (sqlite backup API) with private permissions."""
    destination = Path(target)
    fd = os.open(str(destination), os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    os.close(fd)
    os.chmod(str(destination), 0o600)
    source = sqlite3.connect("file:%s?mode=ro" % quote(str(db)), uri=True, timeout=30)
    copy = sqlite3.connect(str(destination))
    try:
        source.backup(copy)
    finally:
        copy.close()
        source.close()
    os.chmod(str(destination), 0o600)
    return destination


# -- install / uninstall / rollback / status ----------------------------------------------
def _backup(reg, previous, db=None, root=None):
    version = re.sub(r"[^A-Za-z0-9._-]", "_", str(previous.get("version", "unknown")))
    root_dir = _private_dir(reg / "backups")
    n = 0
    while (root_dir / ("%s-%d" % (version, n))).exists():
        n += 1
    target = _private_dir(root_dir / ("%s-%d" % (version, n)))
    for name, mode in (("registry.json", 0o600), ("current", 0o600), ("bin/boot", 0o700)):
        source = reg / name
        if source.is_file():
            _write(target / name, source.read_text(encoding="utf-8"), mode)
    if db is not None and Path(db).exists():
        _backup_store(db, target / "store.sqlite3")
        _write_json(target / "meta.json", {"root": str(root), "domain_id": paths.domain_id_for_root(root),
                                           "version": previous.get("version")})
    return target


def _record_refusal(reg, key, reason, message):
    """Make a refusal visible in status when the domain is already registered."""
    entry, _error = _load_entry(reg, key)
    if entry is None:
        return
    path = reg / "boot" / (key + ".json")
    state = _read_json(path) or {}
    state["status"] = {"state": "waiting", "reason": reason, "message": message, "at": time.time()}
    _write_json(path, state)


def _start_on_boot(root, env):
    code, value, _error = _config_value(root, "supervisor.start_on_boot", env)
    return code == 0 and value == "true"


def install(root, *, env=None, platform=None, kind="boot", output_dir=None, install_dir=None, apply=False,
            credentials=(), runner=subprocess.run, live_status=None):
    """Register the domain at root and render its service file. Never starts work.

    Returns a result dict. Activation commands that need no administrator run only with
    apply=True; a macOS LaunchDaemon is never installed from here, its privileged commands are
    returned for a person to run. An upgrade that this runtime cannot safely take over (a store
    schema or an active attempt's runner protocol it does not speak, or a live service with
    active attempts on another protocol) is refused before anything is changed."""
    env = os.environ if env is None else env
    live_status = live_status or _live_status
    root = Path(root).resolve(strict=True)
    platform = _platform(platform)
    if kind not in ("boot", "login") or (platform == "linux" and kind == "login"):
        raise errors.Invalid("unsupported service kind %r for %s" % (kind, platform))
    credentials = sorted(set(credentials))
    for name in credentials:
        if not _NAME.match(name):
            raise errors.Invalid("credential must be an environment variable name: %r" % name)
    key = domain_key(root)
    label, unit = _names(root, key, platform, kind)
    reg = _private_dir(registry_dir(env))
    user = current_user()
    home = str(_home(env))
    log_dir = paths.log_dir(env).absolute()
    socket_base = paths.socket_base(env).absolute()
    paths.socket_dir(paths.domain_id_for_root(root), base=socket_base)  # refuses a base that is too long
    db = _store_path(log_dir, root)
    try:
        info = _read_store_file(db)
    except sqlite3.Error as exc:
        raise errors.Invalid("supervisor state cannot be read: %s" % str(exc)[:200])
    live = live_status(root, {"socket_dir": str(socket_base)})
    warnings = []
    for reason, message in compatibility(info, live):
        active = (info or {}).get("active", 0) or ((live or {}).get("queue") or {}).get("running", 0)
        if reason == "incompatible_protocol" and not active:
            warnings.append(message + " (no attempts are active; restart the service after the upgrade)")
            continue
        _record_refusal(reg, key, reason, message)
        raise errors.Invalid("install refused (%s): %s" % (reason, message))
    executables = _executables(env)
    version = plugin_version()
    previous = _read_json(reg / "registry.json")
    backup = None
    old_launcher = reg / "bin" / "boot"
    changed = bool(previous) and (previous.get("version") != version or
                                  (old_launcher.is_file() and old_launcher.read_text(encoding="utf-8") != LAUNCHER))
    if changed:
        backup = _backup(reg, previous, db, root)
    scripts_dir = str(Path(__file__).resolve().parents[1])
    _write_json(reg / "registry.json", {"schema": 1, "version": version, "protocol": PROTOCOL_VERSION,
                                        "python": executables["python"], "scripts_dir": scripts_dir,
                                        "executables": executables})
    _write(reg / "current", executables["python"] + "\n" + scripts_dir + "\n")
    _write(reg / "bin" / "boot", LAUNCHER, 0o700)
    launcher_path = str(reg / "bin" / "boot")

    # The store starts stopped: setup alone never authorizes work on a never-started board.
    from .store import Store
    Store.open(paths.board_domain(root, log_dir / "supervisor")).close()
    _private_dir(log_dir)
    info = _read_store_file(db)

    environment = {"HOME": home, "PATH": _service_path(env, executables), "PYTHON": executables["python"],
                   "FLEET_BOARD_SOCKET_DIR": str(socket_base), "FLEET_BOARD_LOG_DIR": str(log_dir),
                   "FLEET_BOARD_REGISTRY_DIR": str(reg)}
    argv = ["/bin/bash", launcher_path, "--domain", str(root)]
    log_path = str(log_dir / "supervisor-boot.log")
    out = Path(output_dir) if output_dir else _private_dir(reg / "rendered")
    out.mkdir(parents=True, exist_ok=True)
    if platform == "darwin":
        text = render_launchd(label, argv, environment, log_path, home, user if kind == "boot" else None)
        rendered = out / (label + ".plist")
        default_dir = Path("/Library/LaunchDaemons") if kind == "boot" else _home(env) / "Library" / "LaunchAgents"
        dest = (Path(install_dir) if install_dir else default_dir) / (label + ".plist")
        if kind == "boot":
            dest = Path("/Library/LaunchDaemons") / (label + ".plist")  # a daemon only ever lives here
    else:
        text = render_systemd(root.name, argv, environment, log_path)
        rendered = out / unit
        default_dir = _home(env) / ".config" / "systemd" / "user"
        dest = (Path(install_dir) if install_dir else default_dir) / unit
    rendered.write_text(text, encoding="utf-8")
    os.chmod(str(rendered), 0o644)

    # RunAtLoad starts the boot entry as soon as the unit is bootstrapped. With start_on_boot true
    # and a running or paused domain that entry restores it, so say so instead of claiming no work.
    restores = _start_on_boot(root, env) and (info or {}).get("mode") in ("running", "paused")
    result = {"registry_dir": str(reg), "launcher": launcher_path, "label": label, "unit": unit,
              "platform": platform, "kind": kind, "rendered": str(rendered), "destination": str(dest),
              "version": version, "protocol": PROTOCOL_VERSION, "backup": str(backup) if backup else None,
              "boot_before_login": platform == "darwin" and kind == "boot",
              "login_fallback": platform == "darwin" and kind == "login",
              "commands": [], "privileged_commands": [], "diagnostics": {}, "failed": [], "applied": False,
              "started_work": False, "will_start_work_on_load": bool(restores and platform == "darwin"),
              "warnings": warnings}
    user_name = current_user()
    if platform == "darwin" and kind == "boot":
        result["privileged_commands"] = [
            ["sudo", "install", "-m", "644", "-o", "root", "-g", "wheel", str(rendered), str(dest)],
            ["sudo", "launchctl", "bootstrap", "system", str(dest)]]
        result["note"] = "A LaunchDaemon needs administrator rights: run the privileged commands yourself."
    elif platform == "darwin":
        result["note"] = "LaunchAgent: starts at login only (a fallback, not boot-before-login)."
        if apply:
            _private_dir_free(dest.parent)
            shutil.copyfile(str(rendered), str(dest))
            domain = "gui/%d" % os.getuid()
            _run(runner, ["launchctl", "bootout", "%s/%s" % (domain, label)])
            step = _run(runner, ["launchctl", "bootstrap", domain, str(dest)])
            result["commands"].append(_brief(step))
            result["applied"] = step.get("returncode") == 0
            if not result["applied"]:
                result["failed"].append(_brief(step))
            result["started_work"] = bool(result["applied"] and restores)
        else:
            result["commands"] = [["launchctl", "bootstrap", "gui/%d" % os.getuid(), str(dest)]]
    else:
        result["diagnostics"]["enable_lingering_command"] = ["loginctl", "enable-linger", user_name]
        if apply:
            _private_dir_free(dest.parent)
            shutil.copyfile(str(rendered), str(dest))
            steps = [_run(runner, ["systemctl", "--user", "daemon-reload"]),
                     _run(runner, ["systemctl", "--user", "enable", unit])]
            result["commands"] = [_brief(s) for s in steps]
            result["failed"] = [_brief(s) for s in steps if s.get("returncode") != 0]
            result["applied"] = not result["failed"]
            result["diagnostics"]["lingering"] = _linger(runner, user_name)
        else:
            result["commands"] = [["systemctl", "--user", "daemon-reload"], ["systemctl", "--user", "enable", unit]]
            result["diagnostics"]["lingering"] = "not_checked"
    _write_json(reg / "domains" / (key + ".json"), {
        "root": str(root), "key": key, "log_dir": str(log_dir), "socket_dir": str(socket_base),
        "credentials": credentials, "label": label, "unit": unit, "kind": kind, "platform": platform,
        "user": user_name, "installed_version": version,
        "activation": {"applied": result["applied"], "destination": str(dest), "rendered": str(rendered)}})
    for stale in ((reg / "probe" / (key + ".json")),):
        try:
            stale.unlink()
        except OSError:
            pass
    return result


def _private_dir_free(path):
    """A user-owned destination directory (not part of the registry); created if missing."""
    Path(path).mkdir(parents=True, exist_ok=True)


def _unit_present(entry, dest, runner):
    """Whether the service unit still exists on the host (read-only checks)."""
    if Path(dest).exists():
        return True
    if entry["platform"] == "darwin":
        target = ("system/" if entry["kind"] == "boot" else "gui/%d/" % os.getuid()) + entry["label"]
        return _run(runner, ["launchctl", "print", target]).get("returncode") == 0
    return False


def _forget(reg, key, entry=None):
    for path in (reg / "domains" / (key + ".json"), reg / "probe" / (key + ".json"), reg / "boot" / (key + ".json")):
        try:
            path.unlink()
        except OSError:
            pass
    if entry:
        try:
            Path(entry["activation"]["rendered"]).unlink()
        except OSError:
            pass


def uninstall(root, *, env=None, install_dir=None, apply=False, runner=subprocess.run, live_status=None):
    """Remove this domain's unprivileged service files and, once the unit is really gone, its
    registration. Never touches state. While the unit still exists (a LaunchDaemon, or without
    --apply) the registration is kept as `uninstall_pending` so status stays honest."""
    env = os.environ if env is None else env
    root = Path(root).resolve()
    reg = registry_dir(env)
    key = _key_for(root, reg)
    entry, error = _load_entry(reg, key)
    if entry is None:
        if error:
            _forget(reg, key)
        return {"removed": bool(error), "pending": False, "commands": [], "privileged_commands": [], "failed": [],
                "warning": error["message"] if error else None}
    result = {"removed": False, "pending": False, "label": entry["label"], "unit": entry["unit"], "commands": [],
              "privileged_commands": [], "failed": []}
    try:
        live = (live_status or _live_status)(root, entry)
    except Exception:  # noqa: BLE001 - an unreadable status is "no live service"
        live = None
    if live is not None:
        # Removing the unit ends only the watcher: serve and its runners are detached from it.
        result["running_service"] = True
        result["warning"] = ("a running service answers on this domain's socket and was not stopped; "
                             "uninstall ends only the boot watcher. Stop it with: supervisor stop")
    dest = Path(entry["activation"]["destination"])
    if install_dir:
        dest = Path(install_dir) / dest.name
    if entry["platform"] == "darwin" and entry["kind"] == "boot":
        result["privileged_commands"] = [["sudo", "launchctl", "bootout", "system/" + entry["label"]],
                                         ["sudo", "rm", "-f", str(dest)]]
    elif apply and entry["platform"] == "darwin":
        step = _run(runner, ["launchctl", "bootout", "gui/%d/%s" % (os.getuid(), entry["label"])])
        result["commands"].append(_brief(step))
    elif apply:
        steps = [_run(runner, ["systemctl", "--user", "disable", entry["unit"]])]
        result["commands"] = [_brief(s) for s in steps]
    if apply and not result["privileged_commands"]:
        try:
            dest.unlink()
        except OSError:
            pass
        if entry["platform"] == "linux":
            result["commands"].append(_brief(_run(runner, ["systemctl", "--user", "daemon-reload"])))
    if _unit_present(entry, dest, runner):
        entry["uninstall_pending"] = True
        _write_json(reg / "domains" / (key + ".json"), entry)
        result["pending"] = True
        result["note"] = "the service unit still exists; the registration is kept as uninstall_pending until it is gone"
        return result
    _forget(reg, key, entry)
    result["removed"] = True
    return result


def rollback(*, env=None, restore_store=False, root=None):
    """Restore the runtime (registry record, current pointer, launcher) from the newest backup.
    The store is restored too only when asked, and only while no service holds it."""
    env = os.environ if env is None else env
    reg = registry_dir(env)
    backups = sorted((p for p in (reg / "backups").glob("*") if p.is_dir()), key=lambda p: p.stat().st_mtime)
    if not backups:
        raise errors.Invalid("no previous version to roll back to")
    source = backups[-1]
    record = _read_json(source / "registry.json") or {}
    restored = False
    if restore_store:
        restored = _restore_store(reg, source, root, env)
    for name, mode in (("registry.json", 0o600), ("current", 0o600), ("bin/boot", 0o700)):
        if (source / name).is_file():
            _write(reg / name, (source / name).read_text(encoding="utf-8"), mode)
    return {"restored_version": record.get("version"), "backup": str(source), "store_restored": restored}


def _restore_store(reg, source, root, env):
    if not root:
        raise errors.Invalid("--restore-store needs the domain (--domain or FLEET_BOARD_DOMAIN)")
    backup = source / "store.sqlite3"
    meta = _read_json(source / "meta.json") or {}
    root = Path(root).resolve(strict=True)
    if not backup.is_file() or meta.get("domain_id") != paths.domain_id_for_root(root):
        raise errors.Invalid("the newest backup holds no store for this domain")
    entry, _error = _load_entry(reg, _key_for(root, reg))
    log_dir = Path(entry["log_dir"]) if entry else paths.log_dir(env).absolute()
    db = _store_path(log_dir, root)
    lock_fd = _hold_service_lock(db)  # held for the whole copy: a starting serve reports owner: false
    try:
        _copy_store(backup, db, source)
    finally:
        os.close(lock_fd)
    return True


def _copy_store(backup, db, source):
    if db.exists():
        n = 0
        while (source / ("store-before-restore-%d.sqlite3" % n)).exists():
            n += 1
        _backup_store(db, source / ("store-before-restore-%d.sqlite3" % n))
    original = sqlite3.connect("file:%s?mode=ro" % quote(str(backup)), uri=True, timeout=30)
    target = sqlite3.connect(str(db), timeout=30)
    try:
        original.backup(target)
    finally:
        target.close()
        original.close()


def probe(root, *, env=None, runner=subprocess.run):
    """Ask the service manager (read-only commands) whether the registration is really active."""
    env = os.environ if env is None else env
    reg = registry_dir(env)
    key = _key_for(root, reg)
    entry, error = _load_entry(reg, key)
    if entry is None:
        return {"boot_registration": "missing", "detail": {}, "diagnostics": {},
                "last_error": error or _last_error(reg, key)}
    activation = entry["activation"]
    dest = Path(activation["destination"])
    if entry.get("uninstall_pending"):
        if not _unit_present(entry, dest, runner):
            _forget(reg, key, entry)
        return registration_state(root, env)
    registration, diagnostics = "pending_activation", {}
    if entry["platform"] == "darwin":
        if entry["kind"] == "boot":
            if dest.exists() and _run(runner, ["launchctl", "print", "system/" + entry["label"]]).get("returncode") == 0:
                registration = "verified"
        elif activation.get("applied") and dest.exists():
            target = "gui/%d/%s" % (os.getuid(), entry["label"])
            if _run(runner, ["launchctl", "print", target]).get("returncode") == 0:
                registration = "login_fallback"
    elif activation.get("applied"):
        enabled = _run(runner, ["systemctl", "--user", "is-enabled", entry["unit"]]).get("returncode") == 0
        linger = _linger(runner, entry["user"])
        diagnostics = {"lingering": linger, "enabled": enabled}
        if enabled and linger == "enabled":
            registration = "verified"
        elif enabled and linger == "missing":
            registration = "lingering_missing"
            diagnostics["enable_lingering_command"] = ["loginctl", "enable-linger", entry["user"]]
    _write_json(reg / "probe" / (key + ".json"), {"registration": registration, "diagnostics": diagnostics,
                                                   "at": time.time()})
    state = registration_state(root, env)
    state["diagnostics"] = diagnostics
    return state


def _last_error(reg, key):
    for status in ((_read_json(reg / "boot" / (key + ".json")) or {}).get("status"),
                   _read_json(reg / "runtime-status.json")):
        if isinstance(status, dict) and status.get("state") == "waiting":
            return {"code": status.get("reason"), "message": status.get("message", ""), "at": status.get("at")}
    return None


def registration_state(root, env=None, *, key=None):
    """What the status view reports: read from the real registry, no subprocess. `missing`
    until a registration exists; only a probed, active registration is ever `verified`. A
    malformed entry is `missing` with a `registry_entry_invalid` error, never an exception."""
    env = os.environ if env is None else env
    reg = registry_dir(env)
    key = key or _key_for(root, reg)
    entry, error = _load_entry(reg, key)
    last_error = error or _last_error(reg, key)
    if entry is None:
        return {"boot_registration": "missing", "detail": {}, "last_error": last_error}
    found = _read_json(reg / "probe" / (key + ".json"))
    registration = found.get("registration", "pending_activation") if found else "pending_activation"
    if entry.get("uninstall_pending"):
        registration = "uninstall_pending"
    boot_state = _read_json(reg / "boot" / (key + ".json")) or {}
    detail = {"platform": entry["platform"], "kind": entry["kind"], "label": entry["label"], "unit": entry["unit"],
              "login_fallback": entry["platform"] == "darwin" and entry["kind"] == "login",
              "installed_version": entry.get("installed_version"),
              "boot_status": (boot_state.get("status") or {}).get("state")}
    return {"boot_registration": registration, "detail": detail, "last_error": last_error}


